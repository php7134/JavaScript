//++ and -- operator

//1. Post Increment
//first assign then increase
let a=1;
let b=a++;

console.log(a); //2
console.log(b);//1


let x=-99;
let y=x++;

console.log(x);
console.log(y);

let num=10;
console.log(num++);

console.log(num);

// 2. Pre(before) increment operator:
// First increase then assign
let m= 1;
let n=++m;

console.log(m);
console.log(n);


let u= -1000;
let v= ++u;

console.log(u);
console.log(v);

//3. post(later) decrement

let w=2;
let r= w--;

console.log(w);
console.log(r);


//4. Pre(before) decrement


let s= 2;
let c= --s;

console.log(s);
console.log(c);



let pop=10;
console.log(++pop);//11
console.log(pop);//11

let rest=-9;
console.log(--rest);//-10
console.log(rest)//-10










